export function ilganNote(gan: string | null | undefined): SangunNote | null {
  if (!gan) return null;
  const ch = gan.trim().charAt(0);
  const key = GAN_KEY[ch] ?? (ILGAN_NOTES[ch] ? ch : null);
  return key ? ILGAN_NOTES[key] ?? null : null;
}
