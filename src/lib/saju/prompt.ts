// 시기(대운·세운·월운) 데이터 분리 — 구조/성격 챕터에 시기 데이터를 주면 모델이 자꾸
// "6월·10월"을 끌어다 써서 전 챕터가 같은 말을 반복한다(실측). 지시("쓰지 마")만으론 안 막혀서
// 데이터 자체를 시기 챕터에만 준다. (부수 효과: 비-시기 챕터 입력 토큰 대폭 절약 — 월운 12개월 등)
function stripTimingFromKeyFacts(keyFacts: string): string {
  return keyFacts
    .split("\n")
    .filter((l) => !/^- (현재 대운|다음 대운|올해\(|돈이 들어오는 달|돈이 새는|인연이 들어오는 달|마음이 흔들리는 달|인연이 가장 크게)/.test(l))
    .join("\n");
}
function stripTimingSections(saju: string): string {
  return saju
    .split(/\n\n(?=\[)/)
    .filter((block) => !/^\[(대운|세운|월운)/.test(block))
    .join("\n\n");
}

/** 상품의 챕터 짧은 제목 목록 — 설계도(blueprint)와 달 배정표가 장을 찾을 때 쓴다.
 *  buildChapterPrompts 의 heading 과 같은 규칙(★ 제거 + " — " 앞부분)으로 만든다. */
export function outlineTitles(productSlug: string): string[] {
  const style = resolveStyle(productSlug);
  return style.outline.map((s) => s.replace(/^★\s*/, "").split(" — ")[0]);
}

/** **티저가 약속한 핵심 장**의 번호(0-based) — ★ 표시 장과 고민/물음 장.
 *  이 장들이 빠진 결과지는 티저에서 판 물건과 다른 물건이다. 출고 게이트가 여기를 본다:
 *  나머지 장이 몇 개 비는 건 크론이 이어 채우면 되지만, 핵심 장이 빈 채로는 안 나간다. */
export function coreChapterIndexes(productSlug: string): number[] {
  return resolveStyle(productSlug)
    .outline.map((title, i) => ({ title, i }))
    .filter(({ title }) => title.startsWith("★") || /고민|물음/.test(title))
    .map(({ i }) => i);
}

export function buildChapterPrompts(input: PromptInput): {
  title: string;
  chapters: ChapterPrompt[];
} {
  const style = resolveStyle(input.productSlug);
  const m = input.myeongsik;
  const pillar = (p: { cheongan: string; jiji: string } | null) =>
    p ? `${p.cheongan}${p.jiji}` : "(시 미상)";

  const baseSaju = input.manseryeokText
    ? `[사주 풀 명식]\n${input.manseryeokText}`
    : [
        `[사주 4기둥]`,
        `- 년주: ${pillar(m.year)}`,
        `- 월주: ${pillar(m.month)}`,
        `- 일주: ${pillar(m.day)}`,
        `- 시주: ${pillar(m.hour)}`,
      ].join("\n");
  // 확정 사실 카드를 맨 위에 둬서, 모델이 나이·대운·세운·일간·용신을 추론하지 않고 그대로 인용하게 함.
  const sajuSectionFull = input.keyFacts ? `${input.keyFacts}\n\n${baseSaju}` : baseSaju;
  // 비-시기 챕터용: 대운·세운·월운 데이터를 뺀 버전(구조·성격에 집중시키고 시기 반복 차단)
  const baseSajuCore = stripTimingSections(baseSaju);
  const sajuSectionCore = input.keyFacts
    ? `${stripTimingFromKeyFacts(input.keyFacts)}\n\n${baseSajuCore}`
    : baseSajuCore;

  const displayName = input.name?.trim();
  const title = displayName
    ? style.title.replace("○○", displayName)
    : style.title.replace("○○님", "당신");

  // "[프로필] 직업: …" 태그는 고민이 아니라 독자 상황 정보 — 스토리 선택지(산군)에서 수집돼 개인화 근거로만 쓴다.
  const profileTags = input.concerns
    .filter((c) => c.startsWith("[프로필]"))
    .map((c) => c.replace("[프로필]", "").trim());
  const realConcerns = input.concerns.filter((c) => !c.startsWith("[프로필]"));
  const hasConcern = realConcerns.length > 0;
  const baseInfo = `[기본 정보]
- 생년월일: ${input.birthDate}${input.timeUnknown ? " (태어난 시각 모름)" : input.birthTime ? ` ${input.birthTime}` : ""}
- 성별: ${input.gender === "male" ? "남성" : "여성"}
- 고민 키워드: ${hasConcern ? realConcerns.join(", ") : "(선택 안 함)"}${profileTags.length ? `\n- 독자 상황: ${profileTags.join(" · ")} — 조언을 이 상황에 맞춰 구체화하되, 사주 근거 없이 상황만으로 단정하지 말 것` : ""}`;

  // 각 챕터를 독립 호출로. 다른 챕터 제목들을 알려줘 "그건 거기서 다루니 쓰지 마"로 중복/이탈 방지.
  const allTitles = style.outline.map((s, i) => `${i + 1}. ${s.replace(/^★\s*/, "")}`);

  const chapters: ChapterPrompt[] = style.outline.map((sectionTitle, i) => {
    const clean = sectionTitle.replace(/^★\s*/, "");
    const heading = `### ${i + 1}. ${clean.split(" — ")[0]}`;
    const others = allTitles.filter((_, j) => j !== i).join(" / ");
    const isConcern = /고민|물음/.test(sectionTitle);
    // ★ 표시 챕터는 상품의 핵심 챕터 — 고민 챕터와 같은 심화 분량을 준다.
    const isCore = sectionTitle.startsWith("★");
    // 분량이 아니라 **밀도**를 지시한다(형님 지시 2026-08-08: 글자수만 많은 건 목표가 아니다).
    // 타이트 실측에서 배운 값어치의 구조: 근거(명식) → 장면(독자의 실제 생활 장면) → 행동(해라/마라).
    // "○○자로 써라"는 채워넣기를 부르고, 이 3박자는 파고들기를 부른다 — 길이는 부산물로 따라온다.
    // 2026-08-25 형님 검토("술술 읽히게") — 3박자를 한 단락에 몰면 4~6문장짜리 벽이 된다.
    // 타이트·청월당 실측: 저쪽 문단은 2~3문장이고, 굵은 키워드만 훑어도 요지가 잡힌다.
    // 밀도(내용)는 지키고 **호흡(형태)**만 바꾼다 — 같은 3박자를 여러 단락에 나눠 싣는 것.
    const density =
      "①명식 근거 → ②그 사람 생활에서 벌어지는 실제 장면 → ③해라/마라 행동, 세 박자를 갖추세요. 단, 세 박자를 한 단락에 몰아넣지 말고 두세 단락에 나눠 담으세요 — **한 단락은 세 문장을 넘기지 않습니다**(길어지면 그 자리에서 단락을 끊으세요). 단락마다 손에 잡히는 구절 하나에만 굵게(**)를 쳐서, 굵은 글씨만 훑어도 그 단락의 요지가 잡히게 하세요. 장면 없이 성격 형용사만 늘어놓는 문장, 근거 없이 좋은 말만 하는 문장은 쓰지 마세요.";
    const lenHint = isConcern || isCore
      ? `이 챕터는 결과지의 핵심입니다 — 소제목마다 깊게. ${density}`
      : /당부|행동/.test(sectionTitle)
        ? "번호 매긴 3가지, 각 1~2문장의 구체적 실천"
        : density;

    const concernLine =
      isConcern && hasConcern
        ? `\n■ 독자가 고른 고민(${realConcerns.join(", ")})을 명식 근거로 정면으로, 올해/시기 조언까지 구체적으로 답하세요.`
        : isConcern
          ? `\n■ 고민을 따로 선택하지 않았으니 "고민이 없다"는 말은 쓰지 말고, 이 명식에서 가장 두드러진 영역(재물/일/관계/건강 중)을 골라 깊게 다루세요.`
          : "";

    // 반복 방지: '시기'(대운·세운·올해·특정 월) 설명은 시기 중심 챕터에서만. 구조/성격 챕터는 시기 반복 금지.
    //
    // ⚠ 제목 문구만으로 가르면 상품마다 다르게 걸린다 — 인연의 「크게 바뀌는 해」는 잡히는데
    //    결혼의 「결혼하는 해」는 안 잡혔고, 그래서 그 장이 대운·세운 없이 생성돼
    //    모델이 「자료를 보내주세요」라는 안내문을 본문에 뱉었다(2026-08-21 실측).
    //    배정표(monthPlan)가 이미 "이 장이 달/해를 든다"를 알고 있으니 **그걸 1순위 근거로** 쓴다.
    //    「걸어온 길」은 지나온 대운을 짚는 장이라 배정표에 달이 없어도 시기 자료가 필요하다.
    const assigned = input.monthPlan?.[i];
    const ownsTiming = !!assigned && (assigned.allow.length > 0 || assigned.ownsYears);
    const isTiming =
      ownsTiming ||
      /걸어온 길/.test(sectionTitle) ||
      /올해|흐름|시기|조심|고민|들어오는 달|새는 달|바뀌는 해|하는 해/.test(sectionTitle);
    const isAction = /행동/.test(sectionTitle);
    const factsCite = !input.keyFacts
      ? ""
      : isTiming
        ? " 위 [확정 사실]의 나이·대운·세운·시기(예: 6·10월)를 콕 집어 구체적으로 쓰세요. 단, 숫자·간지 값은 새로 지어내지 마세요."
        : isAction
          ? " 위 [확정 사실]을 근거로 하되 대운·세운 설명을 다시 늘어놓지 말고, 바로 실천 가능한 행동에 집중하세요."
          : " 위 [확정 사실]의 일간·오행 분포·십성·용신을 근거로 쓰세요. 오행의 강·약·유무는 [확정 사실]의 '오행 분포' 숫자와 다르게 말하지 마세요. 이 챕터는 타고난 구조·성격·패턴 자체에 집중하세요.";

    // 시기 챕터에만 대운·세운·월운 데이터를 준다(비-시기 챕터의 시기 반복을 데이터 차원에서 차단).
    const sajuSection = isTiming || isAction ? sajuSectionFull : sajuSectionCore;

    // 형광펜은 시스템 규칙에도 있지만 실측(2026-08-06)에서 9챕터 중 4챕터만 지켰다.
    // 챕터별 독립 호출이라 시스템 맨 앞의 규칙이 과제 지시에 묻힌다 — 여기 한 번 더 박는다.
    // 점수 중복도 같은 이유(다른 챕터가 뭘 썼는지 모른다)라, 쓰면 안 되는 챕터에 직접 금지한다.
    // ⚠ 점수를 쓰는 장은 **「○○ 그릇」 장**이다(첫 문장을 "인연/결혼 그릇 ○○점"으로 열라고 지시한다).
    //    「들어오는 달」만 보던 시절엔 그릇 장에 점수 금지가 붙어 지시끼리 충돌했다 —
    //    결혼 1장은 그 충돌로 본문 대신 「점수를 보내주세요」라는 안내문이 나왔다(2026-08-21 실측).
    const isScoreChapter = /들어오는 달|그릇/.test(sectionTitle);
    const scoreBan = input.keyFacts && !isScoreChapter
      ? "\n■ 이 챕터에서는 '재물그릇 ○○점' · '인연 그릇 ○○점' 같은 점수를 쓰지 마세요(점수를 말하는 챕터가 따로 있습니다)."
      : "";

    // 설계도(있으면): 이 장의 주장·소제목·전체 실타래. 과거 서사 장에는 arc 블록을 통째로.
    // 걸어온 길·처방 장에는 결정론 확정값(pastBlock/prescriptionBlock)이 따로 실린다 —
    // LLM 설계도(기본 꺼짐)와 무관하게 항상 들어가는, 표와 같은 계산값이다.
    const bpBlock = [
      /걸어온 길/.test(sectionTitle)
        ? blueprintLines(input.blueprint ?? null, i) + blueprintArcBlock(input.blueprint ?? null) + (input.pastBlock ? `\n${input.pastBlock}` : "")
        : blueprintLines(input.blueprint ?? null, i),
      /산군의 처방/.test(sectionTitle) && input.prescriptionBlock ? `\n${input.prescriptionBlock}` : "",
    ].join("");
    // 배정표(있으면): 이 장이 말할 달 / 달 언급 금지.
    const planLine = monthPlanLine(input.monthPlan?.[i]);

    // 소제목 — 타이트 실측(24,000자 결과지)에서 배운 값어치의 절반. 긴 장을 「네 본질 →
    // 니가 안 보여주는 얼굴 → 열등감의 정체」처럼 2~3덩이로 갈라야 파고드는 구조가 생긴다.
    // 설계도가 소제목을 이미 정했으면 그걸 쓰고(bpBlock 에 지시 포함), 없으면 여기서 직접 시킨다.
    // 당부(번호 목록)·행동 챕터는 제외 — 목록에 소제목을 얹으면 오히려 부스러진다.
    const hasBpSections = !!input.blueprint?.chapters[i]?.sections?.length;
    const sectionLine =
      hasBpSections || /당부|행동/.test(sectionTitle)
        ? ""
        : `\n■ 장 안을 **소제목 ${isCore || isConcern ? "2~3" : "2"}개**로 가르세요 — 소제목은 굵은 글씨 한 줄(**이렇게**)로 세우고, 밋밋한 이름표("성격 분석")가 아니라 읽고 싶어지는 말("네가 숨겨온 얼굴", "돈이 새는 구멍")로 짓습니다. 맨 첫 줄의 장 제목("${heading}")은 그대로 두고, 소제목에만 ### 대신 굵은 글씨를 쓰세요.`;

    const user = `${sajuSection}

${baseInfo}${bpBlock}

지금은 '${title}' 결과지 중 아래 한 챕터만 작성합니다.
■ 이 챕터: ${clean}
■ 쓰는 법: ${lenHint}
■ 다른 챕터(여기서 다루지 마세요): ${others}${planLine}${sectionLine}${concernLine}${scoreBan}
■ **이 챕터에서 가장 중요한 한 문장을 골라 앞뒤를 == 로 감싸세요(==이렇게==). 정확히 한 문장, 반드시 한 번.** 빠뜨리지 마세요.

"${heading}" 소제목으로 시작해, 이 챕터 내용만 쓰세요. 다른 챕터와 같은 문장·같은 사실을 반복하지 말고 이 챕터만의 새로운 내용을 쓰세요. 위 [좋은/나쁜 문장 예시]의 '좋은' 스타일을 반드시 따르세요.${factsCite}${
      input.timeUnknown ? " 태어난 시각을 모르니 시(時)에 의존하는 단정은 피하세요." : ""
    }`;

    return { system: style.voice ? `${SYSTEM_BASE}\n\n${style.voice}` : SYSTEM_BASE, user, heading };
  });

  return { title, chapters };
}

